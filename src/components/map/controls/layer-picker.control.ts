    #renderGibsSvgLegend(layer: BaseLayer, svgContent: string) {
        const name = layer.get('name') ?? ''
        const title = layer.get('title') ?? ''

        const handleMouseOver = (e: MouseEvent) => {
            const target = e.target as SVGElement | null
            const idx = target?.getAttribute('data-tooltip-idx')

            if (!idx) {
                return
            }

            const container = e.currentTarget as HTMLElement
            const tooltip = container.querySelector<SVGElement>(`#tooltip_${idx}`)

            tooltip?.setAttribute('visibility', 'visible')
        }

        const handleMouseOut = (e: MouseEvent) => {
            const target = e.target as SVGElement | null
            const idx = target?.getAttribute('data-tooltip-idx')

            if (!idx) {
                return
            }

            const container = e.currentTarget as HTMLElement
            const tooltip = container.querySelector<SVGElement>(`#tooltip_${idx}`)

            tooltip?.setAttribute('visibility', 'hidden')
        }

        const handleClick = (e: MouseEvent) => {
            e.stopPropagation()
            const rect = (e.target as Element | null)?.closest('rect[data-value]')
            const valueChosen = rect?.getAttribute('data-value')

            if (!valueChosen) {
                return
            }

            this.#options?.onLegendClick?.({
                name,
                title,
                type: 'visualization',
                valueChosen,
                layer,
            })
        }

        return html`
                <div
                    class="layer-picker-legend layer-picker-legend-gibs"
                    role="figure"
                    aria-label="${title} color map legend"
                    @mouseover=${handleMouseOver}
                    @mouseout=${handleMouseOut}
                    @click=${handleClick}
                >
                    ${unsafeSVG(svgContent)}
                </div>
            `
    }
    #renderSection(heading: string, layers: BaseLayer[], type: 'base' | 'overlay') {
        return html`
            <div class="layer-picker-section">
                <div class="layer-picker-heading">${heading}</div>
                ${layers.map(
                    layer => html`
                        <label class="layer-picker-item">
                            <input
                                type=${type === 'base' ? 'radio' : 'checkbox'}
                                name=${ifDefined(
                                    type === 'base'
                                        ? 'terra-map-base-layer'
                                        : undefined
                                )}
                                .checked=${layer.getVisible()}
                                @change=${(e: Event) => {
                                    const input = e.target as HTMLInputElement
                                    if (type === 'base') {
                                        layers.forEach(bLayer => {
                                            bLayer.setVisible(bLayer === layer)
                                        })
                                    } else {
                                        layer.setVisible(input.checked)
                                    }

                                    this.#options?.onLayerToggle?.({
                                        name: layer.get('name') ?? '',
                                        title: layer.get('title') ?? '',
                                        type,
                                        visible: layer.getVisible(),
                                        layer,
                                    })
                                }}
                            />
                            <span>${layer.get('title')}</span>
                        </label>
                    `
                )}
            </div>
        `
    }
